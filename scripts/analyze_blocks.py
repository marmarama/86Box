#!/usr/bin/env python3
"""
analyze_blocks.py - 86Box Dynarec Block Dump Analysis & Linting Tool

Reads binary .86bdump files generated by the 86Box dynarec block dumper
(BOX86_DUMP_BLOCKS=trace.86bdump) and provides:
  1. Side-by-side 3-tier annotated disassembly (--inspect-block <id_or_pc>)
  2. Automated codegen linter & anti-pattern detector (--lint)
  3. Aggregate telemetry & hotspot summary (--summary)

Supports Python Capstone for host and guest machine code disassembly
and automatically symbolizes [rbp + disp] operands to cpu_state fields.
"""

import sys
import os
import struct
import argparse
import re
from collections import defaultdict, Counter

try:
    import capstone
    from capstone import Cs, CS_ARCH_X86, CS_MODE_16, CS_MODE_32, CS_MODE_64, CS_ARCH_ARM64, CS_MODE_ARM
    HAVE_CAPSTONE = True
except ImportError:
    HAVE_CAPSTONE = False

# File Magic & Versions
BDUMP_MAGIC = 0x44423638  # "86BD"
BDUMP_VERSION = 1

# Host Architectures
BDUMP_ARCH_X86_64      = 1
BDUMP_ARCH_ARM64       = 2
BDUMP_ARCH_LOONGARCH64 = 3

ARCH_NAMES = {
    BDUMP_ARCH_X86_64: "x86-64",
    BDUMP_ARCH_ARM64: "ARM64",
    BDUMP_ARCH_LOONGARCH64: "LoongArch64"
}

# Record Types
BDUMP_REC_COMPILE      = 1
BDUMP_REC_EXEC         = 2
BDUMP_REC_HOST_PROFILE = 3

# Exit Types
EXIT_TYPE_NAMES = {
    0: "BLOCK_EXIT_NONE",
    1: "BLOCK_EXIT_DIRECT_1",
    2: "BLOCK_EXIT_COND_2",
    3: "BLOCK_EXIT_RET"
}

# Invalidation Reasons
INVALIDATE_REASON_NAMES = {
    0: "VM Exit / Shutdown",
    1: "SMC Dirty Flush",
    2: "Cache Eviction"
}

# x86-64 Host Register Names
HOST_REGS_X86_64 = {
    0: "rax", 1: "rcx", 2: "rdx", 3: "rbx",
    4: "rsp", 5: "rbp", 6: "rsi", 7: "rdi",
    8: "r8",  9: "r9",  10: "r10", 11: "r11",
    12: "r12", 13: "r13", 14: "r14", 15: "r15"
}

# ARM64 Host Register Names
HOST_REGS_ARM64 = {i: f"x{i}" for i in range(31)}
HOST_REGS_ARM64[31] = "sp"

# LoongArch64 Host Register Names
HOST_REGS_LOONGARCH64 = {
    0: "zero", 1: "ra", 2: "tp", 3: "sp",
    4: "a0", 5: "a1", 6: "a2", 7: "a3", 8: "a4", 9: "a5", 10: "a6", 11: "a7",
    12: "t0", 13: "t1", 14: "t2", 15: "t3", 16: "t4", 17: "t5", 18: "t6", 19: "t7", 20: "t8",
    21: "r21", 22: "fp/s9", 23: "s0", 24: "s1", 25: "s2", 26: "s3", 27: "s4", 28: "s5", 29: "s6", 30: "s7", 31: "s8"
}

# Parse C headers if available for complete IREG and UOP definitions
def load_c_definitions():
    iregs = {}
    uops = {}
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    reg_h = os.path.join(base_dir, "src", "codegen_new", "codegen_reg.h")
    ir_defs_h = os.path.join(base_dir, "src", "codegen_new", "codegen_ir_defs.h")

    if os.path.exists(reg_h):
        with open(reg_h, "r", errors="ignore") as f:
            text = f.read()
        m = re.search(r"enum\s*\{(.*?)\};", text, re.DOTALL)
        if m:
            val = 0
            for item in m.group(1).split(","):
                item = item.strip()
                if not item or item.startswith("/*") or item.startswith("//"):
                    continue
                parts = item.split("=")
                name = parts[0].strip().split()[0]
                if len(parts) > 1:
                    try:
                        val = int(parts[1].strip(), 0)
                    except Exception:
                        pass
                if name.startswith("IREG_"):
                    iregs[val] = name
                    val += 1

    if os.path.exists(ir_defs_h):
        with open(ir_defs_h, "r", errors="ignore") as f:
            for line in f:
                m = re.match(r"#\s*define\s+(UOP_[A-Za-z0-9_]+)\s+(.*)", line)
                if m:
                    name = m.group(1)
                    expr = m.group(2).strip()
                    hex_match = re.search(r"\|\s*(0x[0-9a-fA-F]+|\d+)\b(?:\s*\|)?", expr)
                    if hex_match:
                        try:
                            val = int(hex_match.group(1), 0)
                            uops[val] = name
                        except Exception:
                            pass

    return iregs, uops

IREG_NAMES, UOP_NAMES = load_c_definitions()

def get_ireg_name(reg_id):
    if reg_id == 255 or reg_id == 0xffff:
        return "NONE"
    base_id = reg_id & 0xff
    size = (reg_id >> 8) & 7
    size_suffix = ["l", "w", "b", "bh", "d", "q", "", ""][size]
    name = IREG_NAMES.get(reg_id, IREG_NAMES.get(base_id, f"IREG_{base_id}"))
    if size != 0 and not name.endswith(f"_{size_suffix.upper()}") and not name.endswith(size_suffix):
        name = f"{name}.{size_suffix}"
    return name

def get_uop_name(uop_type):
    opcode = uop_type & 0xffff
    return UOP_NAMES.get(opcode, f"UOP_0x{opcode:02x}")

def get_host_reg_name(reg_idx, arch):
    if reg_idx < 0:
        return ""
    if arch == BDUMP_ARCH_X86_64:
        base_reg = reg_idx & 0xf
        return HOST_REGS_X86_64.get(base_reg, f"r{base_reg}")
    elif arch == BDUMP_ARCH_ARM64:
        base_reg = reg_idx & 0x1f
        return HOST_REGS_ARM64.get(base_reg, f"x{base_reg}")
    elif arch == BDUMP_ARCH_LOONGARCH64:
        base_reg = reg_idx & 0x1f
        return HOST_REGS_LOONGARCH64.get(base_reg, f"r{base_reg}")
    return f"reg{reg_idx}"

class BDumpFile:
    def __init__(self, filename):
        self.filename = filename
        self.header = None
        self.symbols = {}       # offset -> name
        self.symbols_sorted = [] # sorted (offset, name)
        self.blocks = []        # list of CompileRecord
        self.blocks_by_nr = {}  # block_nr -> list of CompileRecord
        self.blocks_by_seq = {} # compile_seq -> CompileRecord
        self.exec_records = []  # list of ExecRecord
        self.host_profile = None # bdump_host_profile_t
        self._parse()

    def _parse(self):
        with open(self.filename, "rb") as f:
            data = f.read()

        offset = 0
        file_len = len(data)
        if file_len < 34:
            raise ValueError("File too small to be a valid .86bdump")

        # Header format: < I H H Q Q Q H
        magic, version, host_arch, cpu_state_addr, readlookup2_addr, ram_addr, symbol_count = \
            struct.unpack_from("<IHHQQQH", data, offset)
        offset += 34

        if magic != BDUMP_MAGIC:
            raise ValueError(f"Invalid magic: 0x{magic:08x} (expected 0x{BDUMP_MAGIC:08x})")
        if version != BDUMP_VERSION:
            raise ValueError(f"Unsupported version: {version}")

        self.header = {
            "magic": magic,
            "version": version,
            "host_arch": host_arch,
            "cpu_state_addr": cpu_state_addr,
            "readlookup2_addr": readlookup2_addr,
            "ram_addr": ram_addr,
            "symbol_count": symbol_count
        }

        # Parse symbol table: < i 28s
        for _ in range(symbol_count):
            if offset + 32 > file_len:
                break
            sym_off, sym_name_bytes = struct.unpack_from("<i28s", data, offset)
            offset += 32
            sym_name = sym_name_bytes.split(b"\x00")[0].decode("ascii", errors="replace")
            self.symbols[sym_off] = sym_name

        self.symbols_sorted = sorted(self.symbols.items(), key=lambda x: x[0])

        # Parse records
        # Compile record format: < B B H I I I I I I H B B H H H H H H Q Q Q
        compile_rec_size = 68
        insn_span_size = 4
        uop_entry_size = 44
        exec_rec_size = 44
        profile_rec_size = 112

        while offset < file_len:
            rec_type = data[offset]
            if rec_type == BDUMP_REC_COMPILE:
                if offset + compile_rec_size > file_len:
                    break
                (rec_type, exit_type, block_nr, compile_seq, pc, _cs, phys, phys_2,
                 status, flags, top, unroll_count, guest_insn_count, guest_byte_len,
                 uop_count, host_byte_len, prologue_end_off, epilogue_pos_off,
                 host_code_addr, page_mask, page_mask2) = struct.unpack_from(
                    "<BBHIIIIIIHBBHHHHHHQQQ", data, offset
                )
                offset += compile_rec_size

                guest_bytes = data[offset : offset + guest_byte_len]
                offset += guest_byte_len

                # Instruction spans
                spans = []
                for _ in range(guest_insn_count):
                    g_off, g_len, op32 = struct.unpack_from("<HBB", data, offset)
                    offset += insn_span_size
                    spans.append({"guest_off": g_off, "guest_len": g_len, "op_32": op32})

                # uOps
                uops = []
                for _ in range(uop_count):
                    (orig_type, final_type, imm_data, func_ptr,
                     dest_reg_a, src_reg_a, src_reg_b, src_reg_c,
                     dest_host_reg, src_host_reg_a, src_host_reg_b, src_host_reg_c,
                     guest_insn_idx, host_start_off, host_body_off, host_end_off) = \
                        struct.unpack_from("<IIIQHHHHhhhhHHHH", data, offset)
                    offset += uop_entry_size
                    uops.append({
                        "orig_type": orig_type,
                        "final_type": final_type,
                        "imm_data": imm_data,
                        "func_ptr": func_ptr,
                        "dest_reg_a": dest_reg_a,
                        "src_reg_a": src_reg_a,
                        "src_reg_b": src_reg_b,
                        "src_reg_c": src_reg_c,
                        "dest_host_reg": dest_host_reg,
                        "src_host_reg_a": src_host_reg_a,
                        "src_host_reg_b": src_host_reg_b,
                        "src_host_reg_c": src_host_reg_c,
                        "guest_insn_idx": guest_insn_idx,
                        "host_start_off": host_start_off,
                        "host_body_off": host_body_off,
                        "host_end_off": host_end_off,
                    })

                host_code = data[offset : offset + host_byte_len]
                offset += host_byte_len

                block = {
                    "rec_type": rec_type,
                    "exit_type": exit_type,
                    "block_nr": block_nr,
                    "compile_seq": compile_seq,
                    "pc": pc,
                    "_cs": _cs,
                    "phys": phys,
                    "phys_2": phys_2,
                    "status": status,
                    "flags": flags,
                    "top": top,
                    "unroll_count": unroll_count,
                    "guest_insn_count": guest_insn_count,
                    "guest_byte_len": guest_byte_len,
                    "uop_count": uop_count,
                    "host_byte_len": host_byte_len,
                    "prologue_end_off": prologue_end_off,
                    "epilogue_pos_off": epilogue_pos_off,
                    "host_code_addr": host_code_addr,
                    "page_mask": page_mask,
                    "page_mask2": page_mask2,
                    "guest_bytes": guest_bytes,
                    "spans": spans,
                    "uops": uops,
                    "host_code": host_code,
                    "exec_count": 0,
                    "host_tsc_total": 0,
                    "host_tsc_callouts": 0,
                    "link0_target_pc": 0,
                    "link1_target_pc": 0,
                    "link0_target_blk": 0xffff,
                    "link1_target_blk": 0xffff,
                    "invalidate_reason": 0
                }
                self.blocks.append(block)
                if block_nr not in self.blocks_by_nr:
                    self.blocks_by_nr[block_nr] = []
                self.blocks_by_nr[block_nr].append(block)
                self.blocks_by_seq[compile_seq] = block

            elif rec_type == BDUMP_REC_EXEC:
                if offset + exec_rec_size > file_len:
                    break
                (rec_type, inv_reason, block_nr, compile_seq, exec_count,
                 host_tsc_total, host_tsc_callouts,
                 link0_pc, link1_pc, link0_blk, link1_blk) = struct.unpack_from(
                    "<BBHIQQQIIHH", data, offset
                )
                offset += exec_rec_size
                exec_rec = {
                    "invalidate_reason": inv_reason,
                    "block_nr": block_nr,
                    "compile_seq": compile_seq,
                    "exec_count": exec_count,
                    "host_tsc_total": host_tsc_total,
                    "host_tsc_callouts": host_tsc_callouts,
                    "link0_target_pc": link0_pc,
                    "link1_target_pc": link1_pc,
                    "link0_target_blk": link0_blk,
                    "link1_target_blk": link1_blk
                }
                self.exec_records.append(exec_rec)
                if compile_seq in self.blocks_by_seq:
                    b = self.blocks_by_seq[compile_seq]
                    b["exec_count"] = exec_count
                    b["host_tsc_total"] = host_tsc_total
                    b["host_tsc_callouts"] = host_tsc_callouts
                    b["link0_target_pc"] = link0_pc
                    b["link1_target_pc"] = link1_pc
                    b["link0_target_blk"] = link0_blk
                    b["link1_target_blk"] = link1_blk
                    b["invalidate_reason"] = inv_reason

            elif rec_type == BDUMP_REC_HOST_PROFILE:
                if offset + profile_rec_size > file_len:
                    break
                (rec_type, resvd, tsc_total, tsc_jit, tsc_c_mem, tsc_c_insn, tsc_c_helper,
                 tsc_c_disp, tsc_c_comp, tsc_c_interp, tsc_c_timers,
                 cnt_disp, cnt_chains, cnt_slow_loads, cnt_slow_stores) = struct.unpack_from(
                    "<B7sQQQQQQQQQQQQQ", data, offset
                )
                offset += profile_rec_size
                self.host_profile = {
                    "tsc_total_cpu_thread": tsc_total,
                    "tsc_jit_pure": tsc_jit,
                    "tsc_c_callout_mem_io": tsc_c_mem,
                    "tsc_c_callout_insn_fn": tsc_c_insn,
                    "tsc_c_callout_helper": tsc_c_helper,
                    "tsc_c_dispatcher": tsc_c_disp,
                    "tsc_c_compiler": tsc_c_comp,
                    "tsc_c_interp_fallback": tsc_c_interp,
                    "tsc_c_timers_devices": tsc_c_timers,
                    "count_c_dispatch_loops": cnt_disp,
                    "count_chained_transfers": cnt_chains,
                    "count_mem_slow_loads": cnt_slow_loads,
                    "count_mem_slow_stores": cnt_slow_stores,
                }
            else:
                # Unknown record or corruption; advance 1 byte
                offset += 1

    def symbolize_operand(self, op_str, host_arch):
        """Resolves [rbp +/- disp] or [x10, #imm] memory references to cpu_state fields."""
        if not self.symbols:
            return None

        # x86-64: RBP = cpu_state + 128
        if host_arch == BDUMP_ARCH_X86_64:
            m = re.search(r"\[\s*rbp\s*([+-])\s*(0x[0-9a-fA-F]+|\d+)\s*\]", op_str)
            if m:
                sign = m.group(1)
                disp = int(m.group(2), 0)
                if sign == "-":
                    disp = -disp
                cpu_off = 128 + disp
                return self._lookup_symbol(cpu_off)

        # ARM64: x10 = &cpu_state
        elif host_arch == BDUMP_ARCH_ARM64:
            m = re.search(r"\[\s*x10(?:,\s*#?(0x[0-9a-fA-F]+|\d+))?\s*\]", op_str)
            if m:
                disp = int(m.group(1), 0) if m.group(1) else 0
                return self._lookup_symbol(disp)

        # LoongArch64: s0 (r23) = &cpu_state
        elif host_arch == BDUMP_ARCH_LOONGARCH64:
            m = re.search(r"\$s0,\s*(-?(?:0x[0-9a-fA-F]+|\d+))", op_str)
            if m:
                disp = int(m.group(1), 0)
                return self._lookup_symbol(disp)

        return None

    def _lookup_symbol(self, cpu_off):
        if cpu_off in self.symbols:
            return f"cpu_state.{self.symbols[cpu_off]}"
        # Find nearest preceding symbol within 32 bytes
        best_sym = None
        best_delta = 9999
        for off, name in self.symbols_sorted:
            if off <= cpu_off and (cpu_off - off) < 32:
                if (cpu_off - off) < best_delta:
                    best_delta = cpu_off - off
                    best_sym = name
        if best_sym:
            return f"cpu_state.{best_sym}+{best_delta}" if best_delta > 0 else f"cpu_state.{best_sym}"
        return f"cpu_state[offset={cpu_off}]"


def disassemble_guest_insn(guest_bytes, op_32, pc):
    if not HAVE_CAPSTONE:
        return f".byte " + " ".join(f"{b:02x}" for b in guest_bytes)

    mode = CS_MODE_32 if (op_32 & 2) else CS_MODE_16
    cs = Cs(CS_ARCH_X86, mode)
    cs.detail = False
    insns = list(cs.disasm(guest_bytes, pc))
    if insns:
        return f"{insns[0].mnemonic} {insns[0].op_str}".strip()
    return f".byte " + " ".join(f"{b:02x}" for b in guest_bytes)


def disassemble_host_code(code_bytes, host_arch, start_addr):
    if not HAVE_CAPSTONE or not code_bytes:
        return []

    if host_arch == BDUMP_ARCH_X86_64:
        cs = Cs(CS_ARCH_X86, CS_MODE_64)
    elif host_arch == BDUMP_ARCH_ARM64:
        cs = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
    else:
        # LoongArch fallback
        lines = []
        for i in range(0, len(code_bytes), 4):
            word_bytes = code_bytes[i:i+4]
            if len(word_bytes) == 4:
                val = struct.unpack("<I", word_bytes)[0]
                lines.append((start_addr + i, f".word 0x{val:08x}", ""))
        return lines

    cs.detail = False
    result = []
    for insn in cs.disasm(code_bytes, start_addr):
        result.append((insn.address, insn.mnemonic, insn.op_str))
    return result


def inspect_block(bdump, target_id):
    """3-Tier side-by-side disassembly with symbolic annotation."""
    # Find matching block
    selected = None
    target_clean = target_id.strip().lower()

    if target_clean.startswith("0x") or any(c in "abcdef" for c in target_clean):
        try:
            target_pc = int(target_clean, 16)
            for b in bdump.blocks:
                if b["pc"] == target_pc or (b["pc"] - b["_cs"]) == target_pc:
                    selected = b
                    break
        except Exception:
            pass

    if not selected:
        try:
            target_nr = int(target_clean)
            for b in bdump.blocks:
                if b["block_nr"] == target_nr or b["compile_seq"] == target_nr:
                    selected = b
                    break
        except Exception:
            pass

    if not selected and bdump.blocks:
        print(f"[-] Block '{target_id}' not found. Showing first compiled block instead.")
        selected = bdump.blocks[0]

    if not selected:
        print("[-] No blocks available in dump file.")
        return

    b = selected
    host_arch = bdump.header["host_arch"]
    arch_str = ARCH_NAMES.get(host_arch, "Unknown")
    exit_str = EXIT_TYPE_NAMES.get(b["exit_type"], f"EXIT_{b['exit_type']}")
    use32_str = "USE32" if (b["status"] & 1) else "USE16"

    # Header banner
    print("=" * 80)
    print(f"BLOCK #{b['block_nr']} (seq {b['compile_seq']}) | PC={b['_cs']>>4:04x}:{b['pc']-b['_cs']:08x} (phys {b['phys']:08x}) | {use32_str} | exec_count={b['exec_count']:,}")
    print(f"Flags: 0x{b['flags']:04x} (TOP={b['top']}) | Exit: {exit_str} -> [0: {b['link0_target_pc']:08x} (blk #{b['link0_target_blk']}), 1: {b['link1_target_pc']:08x} (blk #{b['link1_target_blk']})]")
    if b.get("host_tsc_total", 0) > 0:
        pure_jit = max(0, b["host_tsc_total"] - b["host_tsc_callouts"])
        avg_cyc = b["host_tsc_total"] / max(1, b["exec_count"])
        print(f"Cycles: {b['host_tsc_total']:,} total host TSC ({pure_jit:,} pure JIT, {b['host_tsc_callouts']:,} C callouts) | avg {avg_cyc:.1f} cyc/exec")

    # Compute reg glue bytes vs body bytes
    total_glue_bytes = 0
    total_body_bytes = 0
    for uop in b["uops"]:
        if uop["host_body_off"] > uop["host_start_off"]:
            total_glue_bytes += (uop["host_body_off"] - uop["host_start_off"])
        if uop["host_end_off"] > uop["host_body_off"]:
            total_body_bytes += (uop["host_end_off"] - uop["host_body_off"])

    host_insns = disassemble_host_code(b["host_code"], host_arch, 0)
    glue_pct = (total_glue_bytes / max(1, b["host_byte_len"])) * 100

    print(f"Stats: {b['guest_insn_count']} guest insns ({b['guest_byte_len']} B) -> {b['uop_count']} uOps -> {len(host_insns)} host insns ({b['host_byte_len']} B, {glue_pct:.1f}% reg-flush glue)")
    print("=" * 80)
    print()

    # Prologue
    if b["prologue_end_off"] > 0:
        prologue_code = b["host_code"][:b["prologue_end_off"]]
        prologue_insns = disassemble_host_code(prologue_code, host_arch, 0)
        print("  [Block Prologue +0x00..+0x{:02x}]".format(b["prologue_end_off"]))
        for addr, mnem, op_str in prologue_insns:
            sym = bdump.symbolize_operand(op_str, host_arch)
            sym_comment = f"  ; {sym}" if sym else ""
            print(f"       +{addr:04x}: {mnem:<7} {op_str:<28}{sym_comment}")
        print()

    # Group uOps by guest_insn_idx
    uops_by_insn = defaultdict(list)
    for uop_idx, uop in enumerate(b["uops"]):
        uops_by_insn[uop["guest_insn_idx"]].append((uop_idx, uop))

    # Iterate guest instructions
    for insn_idx, span in enumerate(b["spans"]):
        g_off = span["guest_off"]
        g_len = span["guest_len"]
        g_bytes = b["guest_bytes"][g_off : g_off + g_len]
        hex_bytes = " ".join(f"{byte:02x}" for byte in g_bytes)
        insn_lin = b["pc"] + g_off
        disasm_text = disassemble_guest_insn(g_bytes, span["op_32"], insn_lin)

        print(f"[Guest #{insn_idx}] {b['_cs']>>4:04x}:{insn_lin-b['_cs']:08x}: {hex_bytes:<14} {disasm_text}")

        insn_uops = uops_by_insn.get(insn_idx, [])
        for uop_num, (uop_idx, uop) in enumerate(insn_uops):
            is_last = (uop_num == len(insn_uops) - 1)
            prefix = "  └─" if is_last else "  ├─"
            sub_prefix = "    " if is_last else "  │ "

            uop_name = get_uop_name(uop["final_type"])
            orig_name = get_uop_name(uop["orig_type"])
            dest_str = get_ireg_name(uop["dest_reg_a"])
            src_a_str = get_ireg_name(uop["src_reg_a"])
            src_b_str = get_ireg_name(uop["src_reg_b"])

            # Host reg allocation annotations
            dest_host = get_host_reg_name(uop["dest_host_reg"], host_arch)
            src_host_a = get_host_reg_name(uop["src_host_reg_a"], host_arch)
            src_host_b = get_host_reg_name(uop["src_host_reg_b"], host_arch)

            if dest_host and dest_str != "NONE":
                dest_str = f"{dest_str}({dest_host})"
            if src_host_a and src_a_str != "NONE":
                src_a_str = f"{src_a_str}({src_host_a})"
            if src_host_b and src_b_str != "NONE":
                src_b_str = f"{src_b_str}({src_host_b})"

            # Build argument description
            uop_type = uop["final_type"]
            args_str = ""
            if uop_type & 0x40000000: # IMM
                if dest_str != "NONE":
                    args_str = f"{dest_str:<16} <- 0x{uop['imm_data']:x}"
                else:
                    args_str = f"imm=0x{uop['imm_data']:x}"
            elif uop_type & 0x10000000: # REGS
                if dest_str != "NONE":
                    srcs = [s for s in [src_a_str, src_b_str] if s != "NONE"]
                    args_str = f"{dest_str:<16} <- {', '.join(srcs)}"
            elif uop_type & 0x20000000: # POINTER
                args_str = f"fn=0x{uop['func_ptr']:x}"

            # Check if pruned by DSE or simplified
            opt_tag = ""
            if uop["orig_type"] != uop["final_type"]:
                opt_tag = f" [OPT: {orig_name} -> {uop_name}]"
            elif uop["host_start_off"] == uop["host_end_off"] and uop["host_start_off"] > 0:
                opt_tag = " [PRUNED / COALESCED]"

            print(f"{prefix} uOp #{uop_idx:02d}: {uop_name:<20} {args_str}{opt_tag}")

            # Disassemble host allocator glue
            if uop["host_body_off"] > uop["host_start_off"]:
                glue_slice = b["host_code"][uop["host_start_off"] : uop["host_body_off"]]
                glue_insns = disassemble_host_code(glue_slice, host_arch, uop["host_start_off"])
                for addr, mnem, op_str in glue_insns:
                    sym = bdump.symbolize_operand(op_str, host_arch)
                    sym_comm = f"  ; FLUSH {sym}" if sym else ""
                    print(f"{sub_prefix}  [glue +0x{addr:02x}] {mnem:<7} {op_str:<26}{sym_comm}")

            # Disassemble host uOp body
            if uop["host_end_off"] > uop["host_body_off"]:
                body_slice = b["host_code"][uop["host_body_off"] : uop["host_end_off"]]
                body_insns = disassemble_host_code(body_slice, host_arch, uop["host_body_off"])
                for addr, mnem, op_str in body_insns:
                    sym = bdump.symbolize_operand(op_str, host_arch)
                    sym_comm = f"  ; {sym}" if sym else ""
                    print(f"{sub_prefix}  [body +0x{addr:02x}] {mnem:<7} {op_str:<26}{sym_comm}")

        print()

    # Epilogue
    if b["epilogue_pos_off"] < b["host_byte_len"]:
        epilogue_code = b["host_code"][b["epilogue_pos_off"]:]
        epilogue_insns = disassemble_host_code(epilogue_code, host_arch, b["epilogue_pos_off"])
        print("  [Block Epilogue +0x{:02x}..+0x{:02x}]".format(b["epilogue_pos_off"], b["host_byte_len"]))
        for addr, mnem, op_str in epilogue_insns:
            sym = bdump.symbolize_operand(op_str, host_arch)
            sym_comment = f"  ; {sym}" if sym else ""
            print(f"       +{addr:04x}: {mnem:<7} {op_str:<28}{sym_comment}")
        print()


def run_linter(bdump):
    """Automated Codegen Linter & Anti-Pattern Detector."""
    print("=" * 80)
    print("DYNAREC CODEGEN LINTER & ANTI-PATTERN AUDIT")
    print("=" * 80)

    total_blocks = len(bdump.blocks)
    host_arch = bdump.header["host_arch"]

    flag_wasted_stores = 0
    flag_wasted_cycles = 0
    redundant_pc_writes = 0
    intra_block_thrashing = 0
    ireg_cycles_hazards = 0
    disasm_failures = 0

    flag_reg_bases = {
        IREG_NAMES.get(k, ""): k for k in [8, 9, 10, 11] # flags_op, flags_res, flags_op1, flags_op2
    }

    for b in bdump.blocks:
        uops = b["uops"]
        exec_count = max(1, b["exec_count"])

        # 1. Dead Flag Materialization Across ORDER_BARRIERs
        # Detects flags dirtied, flushed at an order barrier, and then immediately overwritten
        flags_dirtied = False
        flags_flushed = False
        for uop in uops:
            uop_type = uop["final_type"]
            dest_base = uop["dest_reg_a"] & 0xff
            # Check if uop produces flags
            if dest_base in [8, 9, 10, 11]:
                if flags_flushed:
                    # Previous flushed flags were overwritten without ever being read!
                    flag_wasted_stores += 4
                    flag_wasted_cycles += 4 * exec_count
                    flags_flushed = False
                flags_dirtied = True
            elif uop_type & 0x08000000: # ORDER_BARRIER
                if flags_dirtied:
                    flags_flushed = True
                    flags_dirtied = False

        # 2. Fast-Path PC / OldPC Redundant Writes
        # Check if pc / oldpc is written multiple times within the block without exits
        pc_writes = 0
        oldpc_writes = 0
        for uop in uops:
            dest_base = uop["dest_reg_a"] & 0xff
            if dest_base == 12: # IREG_pc
                pc_writes += 1
            elif dest_base == 13: # IREG_oldpc
                oldpc_writes += 1
            elif uop["final_type"] & 0x80000000: # Barrier / potential exit
                pc_writes = 0
                oldpc_writes = 0
        if pc_writes > 1:
            redundant_pc_writes += (pc_writes - 1) * exec_count
        if oldpc_writes > 1:
            redundant_pc_writes += (oldpc_writes - 1) * exec_count

        # 3. Intra-Block Register Thrashing (Spill then Reload)
        # Look for host allocator glue saving and then reloading the same guest reg
        allocated_regs = set()
        for uop in uops:
            # Check glue size
            if uop["host_body_off"] > uop["host_start_off"]:
                # Has allocator glue
                srcs = [uop["src_reg_a"] & 0xff, uop["src_reg_b"] & 0xff]
                for s in srcs:
                    if s in allocated_regs and s < 8: # GPRs
                        intra_block_thrashing += 1
            if uop["dest_reg_a"] != 0xffff:
                allocated_regs.add(uop["dest_reg_a"] & 0xff)

        # 4. IREG_cycles Hazard Detector (Bug C-3 pattern)
        # Check if IREG_cycles (19) is live in a host reg across a memory op and then modified without a full barrier
        cycles_in_host = False
        mem_op_with_cached_cycles = False
        for uop in uops:
            uop_type = uop["final_type"]
            uop_name = get_uop_name(uop_type)
            if (uop["src_reg_a"] & 0xff) == 19 or (uop["dest_reg_a"] & 0xff) == 19:
                if uop["dest_host_reg"] >= 0 or uop["src_host_reg_a"] >= 0:
                    if mem_op_with_cached_cycles and uop_name == "UOP_SUB_IMM" and (uop["dest_reg_a"] & 0xff) == 19:
                        ireg_cycles_hazards += 1
                        mem_op_with_cached_cycles = False
                    cycles_in_host = True
            if uop_type & 0x80000000: # Full UOP_TYPE_BARRIER reloads/invalidates host registers
                cycles_in_host = False
                mem_op_with_cached_cycles = False
            elif uop_name.startswith("UOP_MEM_LOAD_") or uop_name.startswith("UOP_MEM_STORE_"):
                if cycles_in_host:
                    mem_op_with_cached_cycles = True

        # 5. Host Disassembly Sanity Check
        if HAVE_CAPSTONE and b["host_byte_len"] > 0:
            disasmd = disassemble_host_code(b["host_code"], host_arch, 0)
            if not disasmd and b["host_byte_len"] > 0:
                disasm_failures += 1

    print(f"[*] Total Blocks Audited: {total_blocks}")
    print()
    print("1. Dead Flag Materialization Across Barriers:")
    print(f"   - Wasted cpu_state.flags_* Stores: {flag_wasted_stores:,} static, {flag_wasted_cycles:,} dynamic cycles")
    print(f"   - Impact: {'[WARNING] High redundant flag spills detected' if flag_wasted_cycles > 100000 else '[OK] Flag materialization clean'}")
    print()
    print("2. Fast-Path PC / OldPC Write Overhead:")
    print(f"   - Overwritten / Redundant PC Stores: {redundant_pc_writes:,} dynamic writes")
    print(f"   - Impact: {'[NOTICE] pc/oldpc fast-path pruning recommended' if redundant_pc_writes > 10000 else '[OK] PC updates optimal'}")
    print()
    print("3. Intra-Block Register Thrashing:")
    print(f"   - Spill-then-Reload Occurrences: {intra_block_thrashing:,}")
    print(f"   - Impact: {'[WARNING] High register pressure detected' if intra_block_thrashing > 500 else '[OK] Low register spill rate'}")
    print()
    print("4. IREG_cycles Stale-Register Hazard (Bug C-3 Pattern):")
    print(f"   - Unreloaded IREG_cycles Across Memory Helpers: {ireg_cycles_hazards}")
    print(f"   - Status: {'[FAIL] Stale IREG_cycles hazards detected!' if ireg_cycles_hazards > 0 else '[PASS] No stale IREG_cycles hazards'}")
    print()
    print("5. Host Instruction Encoding Sanity:")
    print(f"   - Disassembly Failures: {disasm_failures}")
    print(f"   - Status: {'[FAIL] Invalid host opcodes found!' if disasm_failures > 0 else '[PASS] 100% of host code disassembles cleanly'}")
    print("=" * 80)


def generate_summary(bdump, top_n=25):
    """Aggregate telemetry, hotspot ranking, instruction mix, and exit analysis."""
    print("=" * 80)
    print("86BOX DYNAREC AGGREGATE TELEMETRY & HOTSPOT SUMMARY")
    print("=" * 80)

    total_blocks = len(bdump.blocks)
    total_execs = sum(b["exec_count"] for b in bdump.blocks)
    host_arch = bdump.header["host_arch"]
    arch_str = ARCH_NAMES.get(host_arch, "Unknown")

    print(f"Host Architecture: {arch_str}")
    print(f"Total Compiled Blocks: {total_blocks:,}")
    print(f"Total Recorded Block Executions: {total_execs:,}")
    print()

    # Host CPU Execution & Profiling Breakdown (Section 4.3)
    if bdump.host_profile:
        hp = bdump.host_profile
        tot_tsc = hp["tsc_total_cpu_thread"] or (
            hp["tsc_jit_pure"] + hp["tsc_c_callout_mem_io"] + hp["tsc_c_callout_insn_fn"] +
            hp["tsc_c_callout_helper"] + hp["tsc_c_dispatcher"] + hp["tsc_c_compiler"] +
            hp["tsc_c_interp_fallback"] + hp["tsc_c_timers_devices"]
        ) or 1
        callouts_tot = hp["tsc_c_callout_mem_io"] + hp["tsc_c_callout_insn_fn"] + hp["tsc_c_callout_helper"]
        inter_block_c = hp["tsc_c_dispatcher"] + hp["tsc_c_compiler"] + hp["tsc_c_interp_fallback"] + hp["tsc_c_timers_devices"]

        print("--- HOST CPU EXECUTION BREAKDOWN (PURE JIT VS C CODE) ---")
        print(f"  Total CPU Thread Host Cycles:    {tot_tsc:<16,d}")
        print(f"  ├─ Pure Native JIT Execution:    {hp['tsc_jit_pure']:<16,d} ({hp['tsc_jit_pure']/tot_tsc*100:6.2f}%)")
        print(f"  ├─ Intra-Block C Callouts:       {callouts_tot:<16,d} ({callouts_tot/tot_tsc*100:6.2f}%)")
        print(f"  │    ├─ Memory Slow-Path I/O:    {hp['tsc_c_callout_mem_io']:<16,d} ({hp['tsc_c_callout_mem_io']/tot_tsc*100:6.2f}%)  [{hp['count_mem_slow_loads']:,} loads, {hp['count_mem_slow_stores']:,} stores]")
        print(f"  │    ├─ Opcode Callouts (IN/OUT):{hp['tsc_c_callout_insn_fn']:<16,d} ({hp['tsc_c_callout_insn_fn']/tot_tsc*100:6.2f}%)")
        print(f"  │    └─ Helpers (flags_rebuild): {hp['tsc_c_callout_helper']:<16,d} ({hp['tsc_c_callout_helper']/tot_tsc*100:6.2f}%)")
        print(f"  └─ Inter-Block C Dispatch/Emul:  {inter_block_c:<16,d} ({inter_block_c/tot_tsc*100:6.2f}%)")
        print(f"       ├─ C Dispatcher Overhead:   {hp['tsc_c_dispatcher']:<16,d} ({hp['tsc_c_dispatcher']/tot_tsc*100:6.2f}%)  [{hp['count_c_dispatch_loops']:,} returns, {hp['count_chained_transfers']:,} chained]")
        print(f"       ├─ JIT Compiler:            {hp['tsc_c_compiler']:<16,d} ({hp['tsc_c_compiler']/tot_tsc*100:6.2f}%)")
        print(f"       ├─ Interpreter Fallback:    {hp['tsc_c_interp_fallback']:<16,d} ({hp['tsc_c_interp_fallback']/tot_tsc*100:6.2f}%)")
        print(f"       └─ Hardware Timers/Devices: {hp['tsc_c_timers_devices']:<16,d} ({hp['tsc_c_timers_devices']/tot_tsc*100:6.2f}%)")
        print()

    # Rank Top Hottest Blocks
    has_tsc = any(b.get("host_tsc_total", 0) > 0 for b in bdump.blocks)
    scored_blocks = []
    for b in bdump.blocks:
        host_insn_count = len(disassemble_host_code(b["host_code"], host_arch, 0)) or max(1, b["host_byte_len"] // 4)
        dynamic_insns = b["exec_count"] * host_insn_count
        sort_metric = b.get("host_tsc_total", 0) if has_tsc else dynamic_insns
        scored_blocks.append((sort_metric, dynamic_insns, host_insn_count, b))

    scored_blocks.sort(key=lambda x: x[0], reverse=True)

    metric_title = "dynamic host TSC cycles" if has_tsc else "dynamic host instructions"
    print(f"--- TOP {min(top_n, len(scored_blocks))} HOTTEST BLOCKS (by {metric_title}) ---")
    if has_tsc:
        print(f"{'Rank':<5} {'Block':<10} {'PC (CS:EIP)':<18} {'Phys':<10} {'Exec Count':<12} {'Host Insns':<11} {'Host TSC':<14} {'Pure JIT':<14} {'Avg Cyc':<9} {'% Tot'}")
        print("-" * 115)
        tot_metric = sum(s[0] for s in scored_blocks) or 1
        for rank, (metric, dyn_insns, h_insns, b) in enumerate(scored_blocks[:top_n], 1):
            pct = (metric / tot_metric) * 100
            cs_eip = f"{b['_cs']>>4:04x}:{b['pc']-b['_cs']:08x}"
            pure_jit = max(0, b.get("host_tsc_total", 0) - b.get("host_tsc_callouts", 0))
            avg_cyc = b.get("host_tsc_total", 0) / max(1, b["exec_count"])
            print(f"#{rank:<4} blk#{b['block_nr']:<6} {cs_eip:<18} {b['phys']:08x}   {b['exec_count']:<12,d} {h_insns:<11,d} {b.get('host_tsc_total', 0):<14,d} {pure_jit:<14,d} {avg_cyc:<9.1f} {pct:5.2f}%")
    else:
        print(f"{'Rank':<5} {'Block':<10} {'PC (CS:EIP)':<18} {'Phys':<10} {'Exec Count':<12} {'Host Insns':<12} {'Total Dyn Insns':<16} {'% Tot'}")
        print("-" * 88)
        tot_metric = sum(s[0] for s in scored_blocks) or 1
        for rank, (metric, dyn_insns, h_insns, b) in enumerate(scored_blocks[:top_n], 1):
            pct = (metric / tot_metric) * 100
            cs_eip = f"{b['_cs']>>4:04x}:{b['pc']-b['_cs']:08x}"
            print(f"#{rank:<4} blk#{b['block_nr']:<6} {cs_eip:<18} {b['phys']:08x}   {b['exec_count']:<12,d} {h_insns:<12,d} {dyn_insns:<16,d} {pct:5.2f}%")
    print()

    # Dynamic Instruction Mix Breakdown
    total_prologue_bytes = 0
    total_epilogue_bytes = 0
    total_glue_bytes = 0
    total_mem_bytes = 0
    total_bookkeeping_bytes = 0
    total_compute_bytes = 0
    total_dynamic_bytes = 0

    for b in bdump.blocks:
        weight = max(1, b["exec_count"])
        total_dynamic_bytes += b["host_byte_len"] * weight
        total_prologue_bytes += b["prologue_end_off"] * weight
        total_epilogue_bytes += (b["host_byte_len"] - b["epilogue_pos_off"]) * weight

        for uop in b["uops"]:
            glue_len = max(0, uop["host_body_off"] - uop["host_start_off"])
            body_len = max(0, uop["host_end_off"] - uop["host_body_off"])
            total_glue_bytes += glue_len * weight

            uop_code = uop["final_type"] & 0xffff
            dest_base = uop["dest_reg_a"] & 0xff

            if uop_code in [0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46]: # MEM ops
                total_mem_bytes += body_len * weight
            elif dest_base in [8, 9, 10, 11, 12, 13]: # flags, pc, oldpc
                total_bookkeeping_bytes += body_len * weight
            else:
                total_compute_bytes += body_len * weight

    print("--- DYNAMIC INSTRUCTION MIX BREAKDOWN ---")
    if total_dynamic_bytes > 0:
        print(f"  Prologue / Frame Setup:       {total_prologue_bytes / total_dynamic_bytes * 100:6.2f}%")
        print(f"  Epilogue / Exit Dispatch:     {total_epilogue_bytes / total_dynamic_bytes * 100:6.2f}%")
        print(f"  Register Allocator Glue:      {total_glue_bytes / total_dynamic_bytes * 100:6.2f}%")
        print(f"  Inlined Memory TLB Fast-Path: {total_mem_bytes / total_dynamic_bytes * 100:6.2f}%")
        print(f"  PC / Flags Bookkeeping:       {total_bookkeeping_bytes / total_dynamic_bytes * 100:6.2f}%")
        print(f"  Core ALU / FPU Computation:   {total_compute_bytes / total_dynamic_bytes * 100:6.2f}%")
    print()

    # Block Exit & Chaining Breakdown
    exit_counts = Counter()
    linked_counts = 0
    unlinked_counts = 0

    for b in bdump.blocks:
        weight = max(1, b["exec_count"])
        exit_counts[b["exit_type"]] += weight
        if b["link0_target_blk"] != 0xffff:
            linked_counts += weight
        else:
            unlinked_counts += weight
        if b["exit_type"] == 2: # COND_2
            if b["link1_target_blk"] != 0xffff:
                linked_counts += weight
            else:
                unlinked_counts += weight

    print("--- BLOCK EXIT & CHAINING EFFICIENCY ---")
    tot_exits = sum(exit_counts.values()) or 1
    for exit_type, cnt in sorted(exit_counts.items()):
        name = EXIT_TYPE_NAMES.get(exit_type, f"TYPE_{exit_type}")
        print(f"  {name:<24}: {cnt:<12,d} ({cnt / tot_exits * 100:5.2f}%)")

    tot_chain_branches = (linked_counts + unlinked_counts) or 1
    print(f"  Chaining Direct Hit Rate:  {linked_counts / tot_chain_branches * 100:5.2f}% ({linked_counts:,} linked branches)")
    print(f"  Chaining Fallback Rate:    {unlinked_counts / tot_chain_branches * 100:5.2f}% ({unlinked_counts:,} unlinked to dispatcher)")
    print()

    # Interpreter Fallback Leaderboard
    fallback_ops = Counter()
    for b in bdump.blocks:
        weight = max(1, b["exec_count"])
        for uop in b["uops"]:
            uop_code = uop["final_type"] & 0xffff
            if uop_code == 0x11: # UOP_CALL_INSTRUCTION_FUNC
                insn_idx = uop["guest_insn_idx"]
                if insn_idx < len(b["spans"]):
                    span = b["spans"][insn_idx]
                    g_bytes = b["guest_bytes"][span["guest_off"] : span["guest_off"] + span["guest_len"]]
                    dis = disassemble_guest_insn(g_bytes, span["op_32"], b["pc"])
                    fallback_ops[dis] += weight

    if fallback_ops:
        print("--- INTERPRETER FALLBACK LEADERBOARD (UOP_CALL_INSTRUCTION_FUNC) ---")
        for op, count in fallback_ops.most_common(10):
            print(f"  {op:<32}: {count:<12,d} dynamic executions")
        print()
    print("=" * 80)


def main():
    parser = argparse.ArgumentParser(description="86Box Dynarec Block Dump Analysis & Linting Tool")
    parser.add_argument("dump_file", help="Path to .86bdump binary file")
    parser.add_argument("--summary", action="store_true", help="Print aggregate telemetry, hotspot ranking, and instruction mix")
    parser.add_argument("--inspect-block", metavar="ID_OR_PC", help="Inspect a specific block by block_nr, compile_seq, or hex PC")
    parser.add_argument("--lint", action="store_true", help="Run automated linter and anti-pattern detector")
    parser.add_argument("--top", type=int, default=25, help="Number of hottest blocks to display in summary (default: 25)")

    args = parser.parse_args()

    if not os.path.exists(args.dump_file):
        print(f"Error: Dump file '{args.dump_file}' does not exist.", file=sys.stderr)
        sys.exit(1)

    try:
        bdump = BDumpFile(args.dump_file)
    except Exception as e:
        print(f"Error parsing '{args.dump_file}': {e}", file=sys.stderr)
        sys.exit(1)

    # If no flags given, default to --summary
    if not args.summary and not args.inspect_block and not args.lint:
        args.summary = True

    if args.summary:
        generate_summary(bdump, top_n=args.top)

    if args.inspect_block:
        inspect_block(bdump, args.inspect_block)

    if args.lint:
        run_linter(bdump)


if __name__ == "__main__":
    main()
